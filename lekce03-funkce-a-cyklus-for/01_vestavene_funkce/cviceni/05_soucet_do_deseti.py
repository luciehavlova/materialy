# Vypiš součet všech čísel od 1 do 10.

print(sum(range(1, 11)))

soucet = 0
for cisla in range(1, 11):
    soucet = soucet + cisla
    print(soucet) # zde vytiskne postupné součty
print(soucet) # zde vypíše konečný součet


      

    

